// Regenerates _lib/i9-b2b-spokes.json (the snapshot of I9's B2B spoke list the "I9 ORDER LIST" uses) from a saved copy of
//   https://b2b.industrynine.com/collections/spokes/products.json?limit=250
// that Jerry saves from his signed-in browser every week (the spoke watcher reads the same file: i9-spoke-watcher in the system-builder folder).
//
//   node scripts/generate-i9-b2b-spokes.mjs <path to i9_spokes_YYYY-MM-DD.json> [--date YYYY-MM-DD] [--out <file>]   (--out: write somewhere else, for tests)
//
// The file date comes from the file name (i9_spokes_2026-11-08.json) or from --date. Nothing is fetched; no I9 page is read by this script or by the webhook.
// One row per variant: exact length (from the SKU inches, as the watcher does; titles round the mm), the gauge family, color, ids, available flag.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith('--') && !(args[args.indexOf(a) - 1] || '').startsWith('--'));
const dateArg = args.includes('--date') ? args[args.indexOf('--date') + 1] : null;
const outArg = args.includes('--out') ? args[args.indexOf('--out') + 1] : null;
const valueArgs = new Set([dateArg, outArg].filter(Boolean));
if (!file) { console.error('usage: node scripts/generate-i9-b2b-spokes.mjs <saved i9_spokes_YYYY-MM-DD.json> [--date YYYY-MM-DD]'); process.exit(1); }

// Gauge families by the diameter part of the SKU "11.810/.114-.106_Black": standard .114-.106 (title "System Spoke - 300mm"), DH .118-.110, straight .114.
const FAMILIES = { '.114-.106': 'standard', '.118-.110': 'dh', '.114': 'straight' };
const parseSku = (sku) => { const m = /^\s*(\d+(?:\.\d+)?)\s*\/\s*(\.\d+(?:-\.\d+)?)\s*_\s*(.*?)\s*$/.exec(String(sku == null ? '' : sku)); return m ? { inches: Number(m[1]), dia: m[2], color: m[3] } : null; };
const titleMm = (t) => { const m = /(\d+(?:\.\d+)?)\s*mm/i.exec(String(t || '')); return m ? Number(m[1]) : null; };

const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
if (/^\s*</.test(text)) { console.error('this file is a web page (probably the login page), not the spokes JSON; save it again while logged in'); process.exit(1); }
const data = JSON.parse(text);
if (!data || !Array.isArray(data.products) || !data.products.length) { console.error('the JSON has no products list'); process.exit(1); }
const nameDate = /(\d{4}-\d{2}-\d{2})/.exec(path.basename(file));
const date = dateArg || (nameDate && nameDate[1]);
if (!/^\d{4}-\d{2}-\d{2}$/.test(String(date))) { console.error('cannot tell the file date: name the file i9_spokes_YYYY-MM-DD.json or pass --date YYYY-MM-DD'); process.exit(1); }

const rows = []; const skipped = [];
for (const p of data.products) {
  const tags = (Array.isArray(p.tags) ? p.tags : String(p.tags || '').split(',')).map((t) => String(t).trim()).filter(Boolean);
  for (const v of p.variants || []) {
    const sk = parseSku(v.sku);
    const tmm = titleMm(p.title);
    if (!sk || tmm == null) { skipped.push(`${p.title} / ${v.title} / ${v.sku}`); continue; }
    const gauge = FAMILIES[sk.dia] || ('other ' + sk.dia);
    rows.push({ mm: Math.round(sk.inches * 25.4 * 10) / 10, titleMm: tmm, gauge, color: String(v.option1 || v.title), variantId: v.id, productId: p.id, handle: p.handle, title: p.title, sku: v.sku, available: v.available === true, price: v.price == null ? null : String(v.price), tags });
  }
}
rows.sort((a, b) => a.mm - b.mm || a.gauge.localeCompare(b.gauge) || a.color.localeCompare(b.color));
const out = {
  source: { file: path.basename(file), date, sha256: crypto.createHash('sha256').update(text).digest('hex'), products: data.products.length, variants: rows.length, note: 'Jerry\'s weekly saved copy of the B2B spokes collection JSON. Generated by scripts/generate-i9-b2b-spokes.mjs. Do not edit by hand.' },
  spokes: rows
};
const outFile = outArg ? path.resolve(outArg) : path.join(root, '_lib', 'i9-b2b-spokes.json');
fs.writeFileSync(outFile, JSON.stringify(out) + '\n');
const byGauge = {}; rows.forEach((r) => { byGauge[r.gauge] = (byGauge[r.gauge] || 0) + 1; });
console.log(`wrote ${path.relative(root, outFile)}: file ${path.basename(file)} (${date}), ${data.products.length} products, ${rows.length} variants`, JSON.stringify(byGauge), `unavailable ${rows.filter((r) => !r.available).length}`, skipped.length ? `SKIPPED ${skipped.length}: ${skipped.slice(0, 3).join(' ; ')}` : '');
