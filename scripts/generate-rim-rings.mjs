// Generates the rim ring data for the build report pictures (round 12) from Agent A's contract and the two ring PNGs kept in _lib/assets/:
//   node scripts/generate-rim-rings.mjs [path-to-rim_photos_contract.json]
// Default contract: ../loamlabs-system-builder/agent-prompts/scs-rim-images/rim_photos_contract.json (the project folder).
// Writes _lib/rim-ring-data.js (the ring geometry, small, loaded eagerly) and _lib/rim-ring-images.js (the PNGs as base64, big, loaded only when a wheel is drawn),
// so nothing is read from disk at run time and the Vercel bundle needs no file tracing. PNG, not WebP: @resvg/resvg-js 2.6.2 draws a WebP data URI as nothing.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = path.resolve(process.argv[2] || path.join(root, '..', 'loamlabs-system-builder', 'agent-prompts', 'scs-rim-images', 'rim_photos_contract.json'));
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
const FILES = { wao: 'rim-wao.png', i9: 'rim-i9.png' };
const NUMS = ['size', 'outerRx', 'outerRy', 'outerAngleDeg', 'outerCx', 'outerCy', 'innerRx', 'innerRy', 'innerAngleDeg', 'innerCx', 'innerCy', 'valveAngleDeg', 'rotationDeg'];

// decalAngleDeg (update 2, I9 only): informational, the angle of the small decal in the photo as supplied; rotationDeg = 360 - decalAngleDeg - valveAngleDeg puts it at 12 o'clock
const OPTIONAL = ['decalAngleDeg'];
const pick = (o) => Object.fromEntries([...NUMS.map((k) => { if (!Number.isFinite(o[k])) throw new Error('contract: bad ' + k); return [k, o[k]]; }), ...OPTIONAL.filter((k) => o[k] !== undefined).map((k) => { if (!Number.isFinite(o[k])) throw new Error('contract: bad ' + k); return [k, o[k]]; })]);
const rings = { wao: pick(contract.wao_front), i9_front: pick(contract.i9_front), i9_rear: pick(contract.i9_rear) };
if (pick(contract.wao).rotationDeg !== 0 || rings.wao.rotationDeg !== 0) throw new Error('WAO rotation is expected to be 0');
// front and rear of one brand share the photo geometry (the rotation may differ per wheel, since update 2 it does not)
for (const k of [...NUMS, ...OPTIONAL].filter((n) => n !== 'rotationDeg')) if (rings.i9_front[k] !== rings.i9_rear[k]) throw new Error('i9 front/rear differ in ' + k);

const bufs = Object.fromEntries(Object.entries(FILES).map(([k, f]) => [k, fs.readFileSync(path.join(root, '_lib', 'assets', f))]));
for (const [k, b] of Object.entries(bufs)) {
  if (b.readUInt32BE(16) !== rings[k === 'wao' ? 'wao' : 'i9_front'].size || b.readUInt32BE(20) !== rings[k === 'wao' ? 'wao' : 'i9_front'].size) throw new Error(`${FILES[k]} is not ${rings.wao.size} px square`);
}
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

fs.writeFileSync(path.join(root, '_lib', 'rim-ring-data.js'), [
  '// _lib/rim-ring-data.js',
  '// GENERATED by scripts/generate-rim-rings.mjs from Agent A\'s rim_photos_contract.json (theme branch agent-a-rim-photos). Do not edit by hand.',
  '// Pixels of the 1024 px ring image, angles in degrees; see _lib/rim-rings.js for how a ring is drawn. rotationDeg: Industry Nine 93.54 front and rear (small decal at the top, update 2), We Are One 0.',
  `export const RING_SOURCE = ${JSON.stringify({ contract: 'rim_photos_contract.json', files: FILES, pngSha256: { wao: sha(bufs.wao), i9: sha(bufs.i9) } })};`,
  `export const RING_GEOMETRY = ${JSON.stringify(rings, null, 1).replace(/\n\s*/g, ' ')};`,
  ''
].join('\n'));
fs.writeFileSync(path.join(root, '_lib', 'rim-ring-images.js'), [
  '// _lib/rim-ring-images.js',
  '// GENERATED by scripts/generate-rim-rings.mjs from _lib/assets/rim-wao.png and rim-i9.png. Do not edit by hand. Loaded only when a wheel picture is drawn.',
  `export const RING_PNG_BASE64 = { wao: '${bufs.wao.toString('base64')}', i9: '${bufs.i9.toString('base64')}' };`,
  ''
].join('\n'));
console.log('wrote _lib/rim-ring-data.js and _lib/rim-ring-images.js', Object.fromEntries(Object.entries(bufs).map(([k, b]) => [k, b.length])));
