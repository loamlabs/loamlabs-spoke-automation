// Generates _lib/valve-color-map.js (round 15) from Agent C's valve color map:
//   node scripts/generate-valve-colors.mjs [path-to-valve_color_map.json]
// Default: ../loamlabs-system-builder/agent-prompts/valve-colors/valve_color_map.json. Written as a JS module (not a JSON import) so the Vercel bundle needs no JSON handling.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.resolve(process.argv[2] || path.join(root, '..', 'loamlabs-system-builder', 'agent-prompts', 'valve-colors', 'valve_color_map.json'));
const map = JSON.parse(fs.readFileSync(src, 'utf8'));
if (!map.default || !/^#[0-9a-f]{6}$/i.test(map.default.hex)) throw new Error('map: bad default');
const out = {};
for (const [k, v] of Object.entries(map)) {
  if (k !== k.toLowerCase().trim()) throw new Error('map: key not lower-case/trimmed: ' + k);
  if (!v || !/^#[0-9a-f]{6}$/i.test(v.hex)) throw new Error('map: bad hex for ' + k);
  out[k] = k === 'default' ? { hex: v.hex.toLowerCase() } : { hex: v.hex.toLowerCase(), light: v.light === true, approximate: v.approximate === true, note: String(v.note || '') };
}
const lines = Object.entries(out).map(([k, v]) => ` ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
fs.writeFileSync(path.join(root, '_lib', 'valve-color-map.js'), [
  '// _lib/valve-color-map.js',
  '// GENERATED by scripts/generate-valve-colors.mjs from Agent C\'s valve_color_map.json (30 store valve stem Color option values, lower-cased and trimmed, plus a default). Do not edit by hand.',
  `export const VALVE_COLOR_MAP = {\n${lines}\n};`,
  ''
].join('\n'));
console.log('wrote _lib/valve-color-map.js with', Object.keys(out).length - 1, 'colors + default');
