// Generates _lib/estimated-extralite-hubs.js from data/extralite-source/ESTIMATED_EXTRALITE_HUB_GEOMETRY.csv (Backend 2's flag list: one line per estimated value, keyed by store variant id).
//   node scripts/generate-extralite-estimated-hubs.mjs [path-to-csv]
// THIS COPY IS THE MASTER, like data/i9-source: change the CSV here (byte for byte, see .gitattributes), run this script, commit the CSV and _lib/estimated-extralite-hubs.js together.
// The script stops when the list is not what the engine expects: not one warning sentence, a line without a variant id, or a variant id that is not digits.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = 'ESTIMATED_EXTRALITE_HUB_GEOMETRY.csv';
const file = path.resolve(process.argv[2] || path.join(root, 'data', 'extralite-source', FILE));
const buf = fs.readFileSync(file); const text = buf.toString('utf8');

export function parseCsv(t) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (q) { if (c === '"') { if (t[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell.replace(/\r$/, '')); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell.replace(/\r$/, '')); rows.push(row); }
  const head = rows[0]; return rows.slice(1).filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((k, i) => [k, r[i]])));
}

const rows = parseCsv(text);
const sentences = [...new Set(rows.map((r) => r.warning))];
if (sentences.length !== 1 || !sentences[0]) { console.error(`STOP: expected ONE warning sentence on every line, found ${sentences.length}`); process.exit(1); }
const variants = {};
for (const r of rows) {
  if (!/^\d+$/.test(r.store_variant_id || '')) { console.error('STOP: a line without a numeric store_variant_id:', JSON.stringify(r).slice(0, 200)); process.exit(1); }
  variants[r.store_variant_id] = { title: r.store_title, spokeCount: r.spoke_count, spacing: r.hub_spacing };
}
const ids = Object.keys(variants);
const out = [
  '// GENERATED by scripts/generate-extralite-estimated-hubs.mjs from data/extralite-source/ESTIMATED_EXTRALITE_HUB_GEOMETRY.csv. Do not edit by hand.',
  '// The Extralite hub variants whose geometry is ESTIMATED from the maker\'s drawings (not measured). An order that uses one of them is flagged "CHECK BEFORE BUILDING" in the',
  '// order note and the builder email (_lib/hub-order-lines.js, api/index.js). Display only: no length, rounding, stock or recipient logic reads this.',
  `export const ESTIMATED_HUB_SOURCE = ${JSON.stringify({ file: FILE, sha256: crypto.createHash('sha256').update(buf).digest('hex'), lines: rows.length, variants: ids.length })};`,
  `export const ESTIMATED_HUB_SENTENCE = ${JSON.stringify(sentences[0])};`,
  '// store variant id (digits) -> which hub variant it is',
  `export const ESTIMATED_HUB_VARIANTS = ${JSON.stringify(variants, null, 1).replace(/\n\s*/g, ' ').replace(/ \}, "/g, ' },\n  "').replace(/^\{ "/, '{\n  "').replace(/ \}$/, '\n}')};`,
  ''
].join('\n');
fs.writeFileSync(path.join(root, '_lib', 'estimated-extralite-hubs.js'), out);
console.log(`wrote _lib/estimated-extralite-hubs.js: ${ids.length} variants, ${rows.length} lines, sha256 ${crypto.createHash('sha256').update(buf).digest('hex').slice(0, 12)}...`);
